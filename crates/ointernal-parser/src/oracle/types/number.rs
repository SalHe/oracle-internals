pub fn get_number_from_bytes(bs: &[u8]) -> Option<u64> {
    // u64 range ok?
    let head = bs[0];
    if head & 0x80 == 0 {
        return None;
    }

    const BASE: u64 = 100;
    if head & 0x40 == 0 {
        return Some(0);
    }

    let mut base = 1;
    let mut value = 0u64;
    let pow = head & 0x0F/* what's the flag range? */;
    for i in (0..pow).rev() {
        let ib = (i as usize) + 1;
        let v = if ib < bs.len() { bs[ib] - 1 } else { 0 };

        value += base * (v as u64);
        base *= BASE;
    }

    Some(value)
}

